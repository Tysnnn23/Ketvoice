// Licences: no GPL artifact may ship (the JavaCPP Presets publish GPL builds under a `-gpl` classifier, e.g.
// ffmpeg-...-windows-x86_64-gpl.jar). Checked on every resolved runtime file, before the tests and any package.
val gplArtifact = Regex("""(?i)(^|[-_.])gpl([-_.]|$)""")
val checkNoGpl by tasks.registering {
    val runtime = configurations.runtimeClasspath
    inputs.files(runtime)
    doLast {
        val names = runtime.get().files.map { it.name }
        val bad = names.filter { gplArtifact.containsMatchIn(it) }
        if (bad.isNotEmpty()) throw GradleException("GPL artifacts on the runtime classpath (Ketvoice ships LGPL builds only): $bad")
        logger.lifecycle("checkNoGpl: ${names.size} runtime files, no GPL artifact")
    }
}
tasks.named("check") { dependsOn(checkNoGpl) }
tasks.test { dependsOn(checkNoGpl) }

