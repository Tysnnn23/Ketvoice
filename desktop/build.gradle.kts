// Shared sources stay in the Android app and are compiled here in place. Each
// manifest in shared/ lists one path or glob per line, relative to the app's
// com/ketvoice/app package; `#` starts a comment.
fun manifest(vararg names: String): List<String> = names.flatMap { name ->
    file("shared/$name.txt").readLines()
        .map { it.substringBefore('#').trim() }
        .filter { it.isNotEmpty() }
        .map { "com/ketvoice/app/$it" }
}

// The app's source roots are added as they are (no copies): a file under an app
// root is compiled only when a manifest lists it; desktop/src is always in.
fun shared(root: File, patterns: List<String>): (FileTreeElement) -> Boolean {
    val spec = PatternSet().include(patterns).asSpec
    return { e -> e.isDirectory || !e.file.startsWith(root) || spec.isSatisfiedBy(e) }
}
// BuildConfig (what Android generates for the shared sources), with the release version.
val generateBuildConfig by tasks.registering {
    val out = layout.buildDirectory.dir("generated/buildconfig")
    val name = appVersion
    val code = versionParts[0] * 10_000 + versionParts[1] * 100 + versionParts[2]
    inputs.property("version", name)
    outputs.dir(out)
    doLast {
        val file = out.get().file("com/ketvoice/app/BuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package com.ketvoice.app
            |
            |/** What Android's generated BuildConfig gives the shared sources, for Ketvoice for Windows (generated by Gradle). */
            |object BuildConfig {
            |    const val DEBUG = false
            |    const val FLAVOR = "desktop"
            |    const val IS_LITE = false
            |    const val IS_QUEST = false
            |    const val VERSION_CODE = $code
            |    const val VERSION_NAME = "$name"
            |}
            |""".trimMargin()
        )
    }
}
