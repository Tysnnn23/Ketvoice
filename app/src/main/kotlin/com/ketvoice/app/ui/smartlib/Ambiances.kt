/**
 * « Ambiances » in the library: playlists generated by mood from what the listener has, each with a
 * generated cover. Built once when shown, refreshed on demand (another selection of each mood).
 */
@Composable
fun AmbiancesShelf(modifier: Modifier = Modifier) {
    val theme = LocalTheme.current
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val mixes by SmartLibrary.mixes.collectAsState()
    val building by SmartLibrary.building.collectAsState()
    LaunchedEffect(Unit) {
        SmartLibrary.init(context)
        if (SmartLibrary.mixes.value.isEmpty()) SmartLibrary.rebuild()
    }
    Column(modifier.fillMaxWidth().testTag("library-ambiances")) {
        Row(Modifier.fillMaxWidth().padding(start = 18.dp, end = 8.dp, top = 16.dp, bottom = 8.dp), verticalAlignment = Alignment.CenterVertically) {
            com.ketvoice.app.ui.common.SectionHeader("Ambiances", Modifier.weight(1f))
            if (building) ActivitySpinner(Modifier.padding(12.dp), size = 18.dp)
            else Box(Modifier.size(44.dp).clip(CircleShape).clickable(role = Role.Button) { scope.launch { SmartLibrary.rebuild(fresh = true) } }
                .testTag("ambiances-refresh"), contentAlignment = Alignment.Center) {
                Icon(KetIcons.Refresh, "Actualiser", tint = theme.accent, modifier = Modifier.size(20.dp))
            }
        }
        if (mixes.isEmpty()) Text(if (building) "Préparation de vos ambiances…" else "Écoutez ou téléchargez quelques titres de plus pour voir vos ambiances.",
            color = theme.secondary, fontSize = 14.sp, modifier = Modifier.padding(horizontal = 18.dp, vertical = 6.dp))
        else LazyRow(contentPadding = PaddingValues(horizontal = 18.dp), horizontalArrangement = Arrangement.spacedBy(14.dp)) {
            items(mixes, key = { it.id }) { mix -> AmbianceCard(mix) }
        }
        Row(Modifier.padding(horizontal = 8.dp, vertical = 6.dp)) {
            KetTextButton("Importer des playlists", { AppUi.openPlaylistImport() }, Modifier.testTag("open-playlist-import"))
            KetTextButton("Doublons", { AppUi.openDuplicates() }, Modifier.testTag("open-duplicates"))
        }
    }
}

@Composable
private fun AmbianceCard(mix: MoodMix) {
    val theme = LocalTheme.current
    Column(Modifier.width(148.dp).clip(RoundedCornerShape(16.dp)).clickable(role = Role.Button) { AppUi.openMood(mix.mood) }
        .testTag("ambiance-" + mix.mood.name)) {
        MoodCover(mix.mood, 148.dp)
        Text(mix.mood.label, color = theme.onBackground, fontSize = 14.sp, fontWeight = FontWeight.SemiBold, maxLines = 1,
            overflow = TextOverflow.Ellipsis, modifier = Modifier.padding(top = 8.dp))
        Text(AppText.t("${mix.tracks.size} titres"), localize = false, color = theme.secondary, fontSize = 12.sp, maxLines = 1)
    }
}

/** The page of one ambiance: its cover, play and shuffle, refresh, save as a playlist, and its titles. */
@Composable
fun MoodScreen() {
    val mood = SmartLibrary.openMood.value ?: return
    val mixes by SmartLibrary.mixes.collectAsState()
    val building by SmartLibrary.building.collectAsState()
    val mix = mixes.firstOrNull { it.mood == mood }
    val context = LocalContext.current
    LaunchedEffect(mood) { SmartLibrary.init(context); if (mixes.isEmpty()) SmartLibrary.rebuild() }
    val theme = LocalTheme.current
    Box(Modifier.fillMaxSize().pageBackground(theme).testTag("mood-screen")) {
        LazyColumn(Modifier.fillMaxSize().statusBarsPadding(),
            contentPadding = PaddingValues(top = 60.dp, bottom = LocalAdaptiveLayout.current.bottomPaddingDp.dp)) {
            item(key = "head") { MoodHeader(mood, mix, building) }
            val tracks = mix?.tracks.orEmpty()
            itemsIndexed(tracks, key = { _, t -> t.id }) { index, track ->
                com.ketvoice.app.ui.common.TrackRow(track, com.ketvoice.app.data.MediaOverrides.cover(track, ArtworkRepo.coverForTrack(track) ?: track.coverUrl),
                    active = false, playing = false, onClick = { Player.setShuffle(false); Player.playQueue(tracks, index) })
            }
        }
        com.ketvoice.app.ui.common.Ket27PageBar(mood.label, { AppUi.closeOverlay() }, Modifier.statusBarsPadding())
    }
}

@Composable
private fun MoodHeader(mood: Mood, mix: MoodMix?, building: Boolean) {
    val theme = LocalTheme.current
    val scope = rememberCoroutineScope()
    var saved by remember(mix) { mutableStateOf<String?>(null) }
    var error by remember { mutableStateOf("") }
    Column(Modifier.fillMaxWidth().padding(horizontal = 20.dp, vertical = 12.dp), horizontalAlignment = Alignment.CenterHorizontally) {
        MoodCover(mood, 220.dp, radius = 20.dp)
        Text(mood.label, color = theme.onBackground, fontSize = 26.sp, fontWeight = FontWeight.Bold, modifier = Modifier.padding(top = 14.dp))
        Text(AppText.t("${mix?.tracks?.size ?: 0} titres") + " · " + AppText.t("D'après votre bibliothèque et vos écoutes"), localize = false,
            color = theme.secondary, fontSize = 13.sp, modifier = Modifier.padding(top = 4.dp, bottom = 14.dp))
        if (mix != null) com.ketvoice.app.ui.common.CollectionPlaybackActions(mix.tracks, Modifier.fillMaxWidth().widthIn(max = 560.dp))
        Row(Modifier.padding(top = 6.dp), verticalAlignment = Alignment.CenterVertically) {
            KetTextButton("Actualiser", { scope.launch { SmartLibrary.rebuild(learn = false, fresh = true) } }, enabled = !building,
                modifier = Modifier.testTag("mood-refresh"))
            KetTextButton(if (saved != null) "Ouvrir la playlist" else "Enregistrer comme playlist", {
                val id = saved
                if (id != null) AppUi.openPlaylist(id) else if (mix != null) scope.launch {
                    runCatching { PlaylistStore.create(AppText.t(mood.label), mix.tracks.map(PlaylistRules::entry)) }
                        .onSuccess { saved = it; error = "" }.onFailure { error = it.message ?: "Impossible d'enregistrer la playlist" }
                }
            }, enabled = mix != null, primary = true, modifier = Modifier.testTag("mood-save"))
        }
        if (error.isNotBlank()) Text(error, color = theme.secondary, fontSize = 13.sp)
        if (mix == null && !building) Text("Pas encore assez de titres pour cette ambiance.", color = theme.secondary, fontSize = 14.sp,
            modifier = Modifier.padding(top = 10.dp))
    }
}
